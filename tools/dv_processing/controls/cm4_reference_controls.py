import numpy as np


def spatial_texture(w, h):
    yy, xx = np.mgrid[:h, :w]
    gray = (0.45 + 0.2 * np.sin(2 * np.pi * xx / 32) * np.cos(2 * np.pi * yy / 16)
            + 0.15 * np.where(xx % 64 >= 32, 1, -1))
    return np.repeat(gray[:, :, None], 3, axis=2).astype(np.float32)


