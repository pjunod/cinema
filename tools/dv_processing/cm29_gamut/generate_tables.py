#!/usr/bin/env python3
"""Generate the CM v2.9 measured-gamut table header from the pinned CSVs."""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = HERE.parent / "dm_cm29_gamut_tables.h"
PEAKS = (600, 1000, 2000)
I_SIZE = 65
C_SIZE = 33
CHROMA_MIN = -16
UNKNOWN = 65535
CSV_FIELDS = ("i", "p", "t", "r", "g", "b")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def peak_code(peak_nits: int) -> int:
    # ST 2084 PQ OETF for normalized luminance, quantized ties-to-even.
    m1 = 2610.0 / 16384.0
    m2 = 2523.0 / 32.0
    c1 = 3424.0 / 4096.0
    c2 = 2413.0 / 128.0
    c3 = 2392.0 / 128.0
    y = (peak_nits / 10000.0) ** m1
    pq = ((c1 + c2 * y) / (1.0 + c3 * y)) ** m2
    return round(pq * 65535.0)


def load_vertices(peak: int, expected_hash: str) -> tuple[list[int], int]:
    path = HERE / f"vertices-{peak}.csv"
    digest = sha256(path)
    if digest != expected_hash:
        raise ValueError(f"{path.name} SHA-256 mismatch: provenance={expected_hash}, actual={digest}")
    limit = peak_code(peak)
    dense = [UNKNOWN] * (I_SIZE * C_SIZE * C_SIZE * 3)
    previous: tuple[int, int, int] | None = None
    seen = 0
    with path.open(newline="", encoding="ascii") as f:
        reader = csv.DictReader(f)
        if tuple(reader.fieldnames or ()) != CSV_FIELDS:
            raise ValueError(f"{path.name}: expected CSV header {','.join(CSV_FIELDS)}")
        for line_no, row in enumerate(reader, start=2):
            try:
                i, p, t, r, g, b = (int(row[name]) for name in CSV_FIELDS)
            except (TypeError, ValueError) as exc:
                raise ValueError(f"{path.name}:{line_no}: all fields must be integers") from exc
            key = (i, p, t)
            if not (0 <= i < I_SIZE and CHROMA_MIN <= p <= 16 and CHROMA_MIN <= t <= 16):
                raise ValueError(f"{path.name}:{line_no}: coordinate outside table domain: {key}")
            if previous is not None and key <= previous:
                reason = "duplicate" if key == previous else "not lexicographically sorted"
                raise ValueError(f"{path.name}:{line_no}: {reason} coordinate {key}")
            channels = (r, g, b)
            if any(value < 0 or value > limit for value in channels):
                raise ValueError(f"{path.name}:{line_no}: channel outside 0..{limit}: {channels}")
            idx = (((i * C_SIZE + (p - CHROMA_MIN)) * C_SIZE + (t - CHROMA_MIN)) * 3)
            if dense[idx] != UNKNOWN:
                raise ValueError(f"{path.name}:{line_no}: duplicate dense coordinate {key}")
            dense[idx:idx + 3] = channels
            previous = key
            seen += 1
    return dense, seen


def render_array(name: str, values: list[int]) -> str:
    lines = [f"static const uint16_t {name}[DM_CM29_GAMUT_I * DM_CM29_GAMUT_C * DM_CM29_GAMUT_C * 3] = {{"]
    for start in range(0, len(values), 24):
        lines.append("  " + ", ".join(str(x) for x in values[start:start + 24]) + ",")
    lines.append("};")
    return "\n".join(lines)


def generate() -> tuple[str, dict[int, int]]:
    provenance_path = HERE / "provenance.json"
    provenance = json.loads(provenance_path.read_text(encoding="utf-8"))
    csv_hashes = provenance.get("exported_csv_sha256")
    if not isinstance(csv_hashes, dict):
        raise ValueError("provenance.json lacks exported_csv_sha256")
    arrays: list[str] = []
    counts: dict[int, int] = {}
    for peak in PEAKS:
        name = f"vertices-{peak}.csv"
        expected = csv_hashes.get(name)
        if not isinstance(expected, str):
            raise ValueError(f"provenance.json lacks hash for {name}")
        values, count = load_vertices(peak, expected)
        counts[peak] = count
        arrays.append(render_array(f"dm_cm29_gamut_{peak}", values))

    body = [
        "/* Generated by cm29_gamut/generate_tables.py; do not edit by hand. */",
        "#ifndef DM_CM29_GAMUT_TABLES_H",
        "#define DM_CM29_GAMUT_TABLES_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "#define DM_CM29_GAMUT_I 65",
        "#define DM_CM29_GAMUT_C 33",
        "#define DM_CM29_GAMUT_R 16",
        f"#define DM_CM29_GAMUT_UNKNOWN UINT16_C({UNKNOWN})",
        "",
        *arrays,
        "",
        "static inline const uint16_t *dm_cm29_gamut_table(double peak_nits, double min_nits, int prim) {",
        "  if (min_nits != 0.005 || prim != 1) return NULL;",
        "  if (peak_nits == 600.0) return dm_cm29_gamut_600;",
        "  if (peak_nits == 1000.0) return dm_cm29_gamut_1000;",
        "  if (peak_nits == 2000.0) return dm_cm29_gamut_2000;",
        "  return NULL;",
        "}",
        "",
        "#endif",
        "",
    ]
    return "\n".join(body), counts


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare generated content without writing")
    args = parser.parse_args()
    content, counts = generate()
    if args.check:
        if not HEADER.is_file() or HEADER.read_text(encoding="ascii") != content:
            print(f"generated header is stale: {HEADER}")
            return 1
    else:
        HEADER.write_text(content, encoding="ascii")
    print(" ".join(f"{peak}:{counts[peak]}" for peak in PEAKS))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
