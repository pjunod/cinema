/** Give sharing a distinct manifest identity and an independently scoped FileProvider. */
class SharingInvitationFileProvider : FileProvider()

/** QR contents stay local and only fill the form; importing still requires a button press. */
@Composable
internal fun SharedSharingInvitationTools(
    secrets: SharedSharingSecretDraft,
    draft: SharedSharingSecretDraft.Snapshot,
    invitationId: String?,
    busy: Boolean,
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var manual by remember(invitationId) { mutableStateOf(false) }
    var notice by remember { mutableStateOf("") }
    var working by remember { mutableStateOf(false) }
    var pickingRevision by remember { mutableStateOf<Long?>(null) }
    var savingRevision by remember { mutableStateOf<Long?>(null) }
    var alive by remember { mutableStateOf(true) }
    val shareDirectory = remember { File(context.cacheDir, "sharing-invitations/" + UUID.randomUUID()) }
    DisposableEffect(secrets) { onDispose { alive = false; shareDirectory.deleteRecursively() } }
    val generated by produceState<Pair<String, Bitmap>?>(null, draft.invitation) {
        value = null
        if (SharedSharingValidation.invitation(draft.invitation)) {
            value = withContext(Dispatchers.Default) { runCatching { draft.invitation to sharingInvitationBitmap(draft.invitation) }.getOrNull() }
        }
    }
    val qr = generated?.takeIf { it.first == draft.invitation }?.second
    val enabled = !busy && !working
    fun accepts(revision: Long) = alive && secrets.accepts(revision)
    fun accept(value: String, revision: Long) {
        if (!accepts(revision)) return
        notice = try {
            if (secrets.acceptInvitation(value, revision)) "Invitation read. Press Import entered invitation to continue." else ""
        } catch (_: IllegalArgumentException) { "That QR code does not contain a Cinema sharing invitation." }
    }
    val imagePicker = rememberLauncherForActivityResult(ActivityResultContracts.GetContent()) { uri ->
        val revision = pickingRevision; pickingRevision = null
        if (uri != null && revision != null && accepts(revision)) scope.launch {
            working = true
            try {
                val value = withContext(Dispatchers.IO) { readSharingInvitationImage(context, uri) }
                accept(value, revision)
            } catch (failure: Exception) {
                if (failure is CancellationException) throw failure
                if (accepts(revision)) notice = "Could not read an invitation QR code. Choose a clear image or enter invitation text."
            } finally { working = false }
        }
    }
    val savePicker = rememberLauncherForActivityResult(ActivityResultContracts.CreateDocument("image/png")) { uri ->
        val revision = savingRevision; savingRevision = null
        if (uri != null && revision != null && accepts(revision)) scope.launch {
            working = true
            try {
                val text = secrets.snapshot()?.takeIf { it.revision == revision }?.invitation ?: return@launch
                val bitmap = withContext(Dispatchers.Default) { sharingInvitationBitmap(text) }
                if (!accepts(revision)) return@launch
                withContext(Dispatchers.IO) {
                    context.contentResolver.openOutputStream(uri)?.use { output ->
                        check(bitmap.compress(Bitmap.CompressFormat.PNG, 100, output))
                    } ?: error("Destination unavailable")
                }
                if (accepts(revision)) notice = "Invitation QR code saved. Send it to the other Cinema."
            } catch (failure: Exception) {
                if (failure is CancellationException) throw failure
                if (accepts(revision)) notice = "Could not save the QR code. Try Share QR code or invitation text."
            } finally { working = false }
        }
    }
    if (draft.invitation.isNotEmpty()) {
        if (qr != null) {
            Image(qr.asImageBitmap(), "Cinema sharing invitation QR code", Modifier.sizeIn(maxWidth = 360.dp, maxHeight = 360.dp).fillMaxWidth().aspectRatio(1f))
            Text("On the other Cinema, open Sharing management and upload or scan this QR code.")
            Button(enabled = enabled, onClick = {
                savingRevision = draft.revision
                try { savePicker.launch("cinema-sharing-invitation.png") }
                catch (_: RuntimeException) { savingRevision = null; notice = "Saving is unavailable. Share the QR code or copy invitation text." }
            }) { Text("Save QR code") }
            Button(enabled = enabled, onClick = { scope.launch {
                val revision = draft.revision; val bitmap = qr
                if (!accepts(revision)) return@launch
                working = true
                try {
                    val file = withContext(Dispatchers.IO) { writeSharingInvitationImage(shareDirectory, bitmap) }
                    if (!accepts(revision)) { file.delete(); return@launch }
                    val uri = FileProvider.getUriForFile(context, context.packageName + ".sharing-files", file)
                    val send = Intent(Intent.ACTION_SEND).setType("image/png").putExtra(Intent.EXTRA_STREAM, uri).addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                    send.clipData = ClipData.newUri(context.contentResolver, "Cinema sharing invitation", uri)
                    context.startActivity(Intent.createChooser(send, "Share invitation QR code"))
                } catch (failure: Exception) {
                    if (failure is CancellationException) throw failure
                    if (accepts(revision)) notice = "Sharing is unavailable. Save the QR code or copy invitation text."
                } finally {
                    working = false
                    if (!alive || secrets.snapshot() == null) shareDirectory.deleteRecursively()
                }
            } }) { Text("Share QR code") }
        } else if (draft.invitation.toByteArray(Charsets.UTF_8).size > SHARING_QR_MAX_BYTES) {
            Text("This invitation is too large for one QR code. Expand Invitation text and copy it instead.")
        }
    }
    TextButton(enabled = enabled, onClick = {
        pickingRevision = draft.revision
        try { imagePicker.launch("image/*") }
        catch (_: RuntimeException) { pickingRevision = null; notice = "Image upload is unavailable. Scan a QR code or enter invitation text." }
    }) { Text("Upload invitation QR code") }
    val canScan = currentFormFactor() != FormFactor.Television && context.packageManager.hasSystemFeature(PackageManager.FEATURE_CAMERA_ANY)
    if (canScan) Button(enabled = enabled, onClick = {
        val revision = draft.revision
        try {
            val options = GmsBarcodeScannerOptions.Builder().setBarcodeFormats(Barcode.FORMAT_QR_CODE).enableAutoZoom().build()
            GmsBarcodeScanning.getClient(context, options).startScan()
                .addOnSuccessListener { accept(it.rawValue.orEmpty(), revision) }
                .addOnFailureListener { if (accepts(revision)) notice = "Camera scanning is unavailable. Upload a QR image or enter invitation text." }
        } catch (_: RuntimeException) {
            if (accepts(revision)) notice = "Camera scanning is unavailable. Upload a QR image or enter invitation text."
        }
    }) { Text("Scan invitation QR code") }
    TextButton(onClick = { manual = !manual }) { Text(if (manual) "Hide invitation text" else "Invitation text") }
    if (manual) {
        OutlinedTextField(keyboardOptions = KeyboardOptions(capitalization = KeyboardCapitalization.None, autoCorrectEnabled = false), value = draft.invitation,
            onValueChange = { secrets.edit(invitation = it) }, label = { Text("Invitation to import or copy") }, enabled = enabled, modifier = Modifier.fillMaxWidth())
        TextButton(enabled = enabled && draft.invitation.isNotEmpty(), onClick = {
            if (accepts(draft.revision)) {
                (context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager).setPrimaryClip(ClipData.newPlainText("Cinema sharing invitation", draft.invitation))
                notice = "Invitation copied."
            }
        }) { Text("Copy invitation text") }
    }
    if (working) Text("Reading or saving QR image…")
    if (notice.isNotEmpty()) Text(notice)
}

/** Never reuse a granted URI for a later invitation: each export owns a new file. */
internal fun writeSharingInvitationImage(directory: File, bitmap: Bitmap): File {
    check(directory.isDirectory || directory.mkdirs()) { "Share directory unavailable" }
    val file = File.createTempFile("cinema-sharing-invitation-", ".png", directory)
    return try {
        file.outputStream().use { check(bitmap.compress(Bitmap.CompressFormat.PNG, 100, it)) }
        file
    } catch (failure: Exception) {
        file.delete()
        throw failure
    }
}

internal fun sharingInvitationBitmap(text: String): Bitmap {
    val matrix = sharingInvitationQR(text)
    val pixels = IntArray(matrix.width * matrix.height) { i -> if (matrix[i % matrix.width, i / matrix.width]) android.graphics.Color.BLACK else android.graphics.Color.WHITE }
    return Bitmap.createBitmap(pixels, matrix.width, matrix.height, Bitmap.Config.ARGB_8888)
}

private fun readSharingInvitationImage(context: Context, uri: android.net.Uri): String {
    val bytes = context.contentResolver.openInputStream(uri)?.use { input ->
        val output = java.io.ByteArrayOutputStream()
        val buffer = ByteArray(8192)
        while (true) {
            val count = input.read(buffer); if (count < 0) break
            require(output.size() + count <= 16 * 1024 * 1024) { "Image exceeds 16 MiB" }
            output.write(buffer, 0, count)
        }
        output.toByteArray()
    } ?: error("Image unavailable")
    val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
    BitmapFactory.decodeByteArray(bytes, 0, bytes.size, bounds)
    require(bounds.outWidth > 0 && bounds.outHeight > 0 && bounds.outWidth.toLong() * bounds.outHeight <= 40_000_000) { "Image dimensions exceed bound" }
    val options = BitmapFactory.Options().apply { inSampleSize = 1 }
    while (maxOf(bounds.outWidth, bounds.outHeight) / options.inSampleSize > 2048) options.inSampleSize *= 2
    val image = BitmapFactory.decodeByteArray(bytes, 0, bytes.size, options) ?: error("Invalid image")
    return try {
        val pixels = IntArray(image.width * image.height)
        image.getPixels(pixels, 0, image.width, 0, 0, image.width, image.height)
        val source = RGBLuminanceSource(image.width, image.height, pixels)
        val reader = QRCodeReader()
        val hints = mapOf(DecodeHintType.TRY_HARDER to true)
        val result = runCatching { reader.decode(BinaryBitmap(HybridBinarizer(source)), hints) }.getOrElse {
            reader.reset(); reader.decode(BinaryBitmap(HybridBinarizer(source.invert())), hints)
        }
        result.text.also { require(SharedSharingValidation.invitation(it)) { "Invalid invitation" } }
    } finally { image.recycle() }
}
