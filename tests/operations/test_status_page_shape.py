"""`STATUS.md` stays a short page, and the status guard follows its prose.

`STATUS.md` is folded from `status.d/` (`scripts/fold`): each effort owns one
file there, so two pull requests never edit the same lines. These checks read
the fold itself, not the committed page, because the page is rewritten after
merge and may lag its folder for one landing.

docs/ci/LEDGER-TEXT-CONTRACTS-AND-RELEASE-TAGS.md §3.4 (M6): older sections
move verbatim into their subject folder's status history, and `STATUS.md`
keeps one row per moved section. A move is only safe if the guard in
`test_status_pr_claims.py` reads the documents the prose moved into —
otherwise the check's reach shrinks silently while the diff looks like a
tidy-up.
"""

from __future__ import annotations

import importlib.machinery
import importlib.util
import sys
from pathlib import Path
import re
import unittest

from test_status_pr_claims import STATUS_PAGES

ROOT = Path(__file__).resolve().parents[2]
STATUS = ROOT / "STATUS.md"
# Five recent efforts in full plus one index row per moved section. Lowered
# from 400 on 2026-10-17 so the page an agent reads at the start of a session
# stays small; when an append crosses it, move the oldest effort out.
MAX_LINES = 180


def _fold_module():
    loader = importlib.machinery.SourceFileLoader("fold_script", str(ROOT / "scripts/fold"))
    spec = importlib.util.spec_from_loader("fold_script", loader)
    module = importlib.util.module_from_spec(spec)
    # Registered before it runs: a dataclass in it looks its module up
    # in sys.modules (Python 3.12 fails on an unregistered one).
    sys.modules[spec.name] = module
    loader.exec_module(module)
    return module


FOLD = _fold_module()


def linked_documents(markdown: str) -> set[str]:
    """Repository-relative Markdown and HTML documents a page links to."""

    targets = set()
    for target in re.findall(r"\]\(([^)\s#]+)(?:#[^)\s]*)?\)", markdown):
        if re.match(r"^[a-z][a-z0-9+.-]*:", target):
            continue
        if target.endswith((".md", ".html")):
            targets.add(target)
    return targets


class StatusPageShapeCase(unittest.TestCase):
    def test_status_md_stays_short(self):
        lines = FOLD.render_status(ROOT).count("\n")
        self.assertLess(
            lines,
            MAX_LINES,
            "STATUS.md has outgrown its page: move the oldest status.d/ entries into "
            "their folder's STATUS-HISTORY.md and leave a row in status.d/INDEX.md",
        )

    def test_every_status_entry_is_one_dated_bullet_or_section(self):
        entries = FOLD.status_entries(ROOT)  # raises FoldError naming the file
        self.assertTrue(entries, "status.d/ holds no effort entries")

    def test_status_md_says_it_is_generated(self):
        self.assertIn("Generated by scripts/fold", STATUS.read_text(encoding="utf-8"))

    def test_every_document_the_index_rows_link_to_is_a_guarded_status_page(self):
        index = (ROOT / FOLD.STATUS_INDEX).read_text(encoding="utf-8").split(
            "## Older efforts — where each one now lives", 1
        )
        self.assertEqual(len(index), 2, "status.d/INDEX.md has no index of moved sections")
        linked = linked_documents(index[1])
        self.assertTrue(linked, "the index of moved sections links to nothing")
        self.assertEqual(sorted(linked - set(STATUS_PAGES)), [])
        for target in linked:
            self.assertTrue((ROOT / target).is_file(), target)


if __name__ == "__main__":
    unittest.main()
